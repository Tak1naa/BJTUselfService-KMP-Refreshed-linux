fn schedule_row(c: &Course, monday: jiff::civil::Date, tz: &jiff::tz::TimeZone) -> Result<Value> {
    let (a, b) = c.time_range(true).ok_or(Error::Malformed("course slot"))?;
    let date = monday
        .checked_add(jiff::Span::new().days(c.weekday() as i64 - 1))
        .map_err(campus_db::storage)?;
    let local = |m: u16| -> Result<String> {
        let z = date
            .at((m / 60) as i8, (m % 60) as i8, 0, 0)
            .to_zoned(campus_core::calendar::school_zone())
            .map_err(campus_db::storage)?
            .with_time_zone(tz.clone());
        Ok(format!("{} {}", z.date(), z.time().strftime("%H:%M")))
    };
    Ok(
        json!({"course_code":c.course_code,"name":c.name,"teacher":c.teacher,"weekday":c.weekday(),"slot":c.slot()+1,"weeks":c.weeks_raw,"place":c.place,"school_time":format!("{:02}:{:02}-{:02}:{:02}",a/60,a%60,b/60,b%60),"local_start":local(a)?,"local_end":local(b)?}),
    )
}

fn data_freshness(
    config: &Config,
    dataset: &str,
    fetched: Option<i64>,
    now: i64,
) -> Result<Freshness> {
    let base = campus_core::freshness(dataset, fetched, now);
    if dataset == "grades"
        && let Some(raw) = config.get("grades.fresh_seconds")
    {
        let ttl = raw
            .parse::<i64>()
            .ok()
            .filter(|t| *t > 0 && *t <= 30 * 86400)
            .ok_or_else(|| Error::Usage("grades.fresh_seconds must be 1..2592000".into()))?;
        if let Some(t) = fetched {
            let age = (now - t).max(0);
            return Ok(if age <= ttl {
                Freshness::Fresh
            } else if age <= 30 * 86400 {
                Freshness::Stale
            } else {
                Freshness::Expired
            });
        }
    }
    Ok(base)
}

fn grade_key(g: &campus_core::Grade) -> String {
    serde_json::to_string(&(&g.course_name, &g.teacher, &g.term))
        .expect("string tuple serialization")
}
fn matches_course_type(g: &campus_core::Grade, types: &[Value], kind: &str) -> bool {
    g.course_code.as_ref().is_some_and(|code| {
        types.iter().any(|v| {
            (v["course_code"] == *code
                || code
                    .get(..8)
                    .is_some_and(|prefix| v["course_code"] == prefix))
                && v["course_type"] == kind
        })
    })
}
